def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--source", choices=["local", "s3"], default="local")
    p.add_argument("--bucket")
    p.add_argument("--prefix", default="content/")
    p.add_argument("--output", default=str(OUTPUT))
    a = p.parse_args()

    if a.source == "s3":
        if not a.bucket:
            sys.exit("--bucket is required with --source s3")
        docs = read_s3(a.bucket, a.prefix)
    else:
        docs = read_local()

    out = pathlib.Path(a.output)
    out.write_text(build(docs), encoding="utf-8")
    print(f"Wrote {out} from {len(docs)} documents ({a.source})")


if __name__ == "__main__":
    main()
