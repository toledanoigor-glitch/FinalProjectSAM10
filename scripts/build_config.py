#!/usr/bin/env python3
"""Build librechat.yaml for the Northbridge University IT Desk from the content documents.

The IT Desk knowledge lives in Markdown files. This script reads them and puts them into
the assistant's instructions (the modelSpec promptPrefix) inside librechat.yaml.

  Local (week 1):  python scripts/build_config.py
  From S3 (week 2): python scripts/build_config.py --source s3 --bucket <bucket> [--prefix content/]

The S3 mode is the project's AWS integration: the content is kept in an S3 bucket
(with versioning on) and the server rebuilds its configuration from there.
Only the Python standard library is needed for local mode; S3 mode needs boto3.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT_DIR = ROOT / "content"
OUTPUT = ROOT / "librechat.yaml"

MODEL = "gemini-3.5-flash"  # tested in LibreChat on 2026-11-16; change here if needed

RULES = """You are Mabi, the virtual assistant of the Northbridge University IT Desk.
You help NBU students and staff with IT questions: NBU accounts and passwords, MFA, Wi-Fi,
VPN, email, NBU Drive, the Software Portal, printing, computer labs and IT policies.

Rules you must always follow:
1. Use ONLY the IT Desk information below. Never invent links, prices, hours, steps or policies.
2. If the answer is not in the information, say you do not know and suggest opening a ticket on
   NBU ServiceHub (https://servicehub.northbridge.example) or emailing itdesk@northbridge.example.
3. NEVER ask for, accept or repeat a password, MFA code or recovery code. If a user types one,
   tell them not to share it and to change their password at https://password.northbridge.example.
4. You cannot reset passwords, unlock accounts, see tickets, see anyone's account or change any
   setting. Explain the self-service steps or how to contact the IT Desk instead.
5. You do not handle grades, enrolment, fees, scholarships or discipline. Send those questions to
   the right office (Registrar, Cashier, Office of Student Affairs) and do not guess outcomes.
6. Do not ask for personal details such as full names, ID numbers, phone numbers or addresses.
7. Give clear numbered steps for how-to questions. Keep answers short: 1 to 6 sentences or a
   short list. Prices are in PHP.
8. Reply in the language the user uses (English, Filipino or Taglish).
9. Politely decline questions that have nothing to do with NBU IT services.

=== IT DESK INFORMATION START ===
"""

RULES_END = "\n=== IT DESK INFORMATION END ==="

GREETING = (
    "Hi, I'm Mabi from the Northbridge University IT Desk. "
    "Ask me about passwords, Wi-Fi, email, printing or the computer labs."
)


def read_local():
    files = sorted(CONTENT_DIR.glob("*.md"))
    if not files:
        sys.exit(f"No .md files found in {CONTENT_DIR}")
    return [(f.name, f.read_text(encoding="utf-8")) for f in files]


def read_s3(bucket, prefix):
    import boto3  # only needed on the server

    s3 = boto3.client("s3")
    resp = s3.list_objects_v2(Bucket=bucket, Prefix=prefix)
    keys = sorted(o["Key"] for o in resp.get("Contents", []) if o["Key"].endswith(".md"))
    if not keys:
        sys.exit(f"No .md files found in s3://{bucket}/{prefix}")
    docs = []
    for key in keys:
        body = s3.get_object(Bucket=bucket, Key=key)["Body"].read().decode("utf-8")
        docs.append((key, body))
    return docs


def block(text, indent):
    """Format text as the body of a YAML literal block (|) at the given indent."""
    pad = " " * indent
    return "\n".join((pad + line) if line.strip() else "" for line in text.splitlines())


def yaml_str(s):
    return "'" + s.replace("'", "''") + "'"


